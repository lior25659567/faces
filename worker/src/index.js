import { ASK, features, promptFor, seedFor, sizeFor, knownOutfit } from './prompt.js'

/**
 * Draws the avatar, so that the phone never holds a Cloudflare token.
 *
 * The iOS app can call Workers AI directly, and while it is running on one developer's device
 * from Xcode that is fine. It is not fine in a build anybody can download: a token on a device
 * is a token its owner can extract, and every call it makes is spent against the account that
 * issued it. This Worker exists so the credential stays here. It reaches Workers AI through the
 * `AI` binding, which means there is no token anywhere in the request path at all — not in the
 * app, not in this source, not in an environment variable.
 *
 * The app already speaks this protocol: `AvatarBackend.worker(url:)` posts a multipart form of
 * `name`, `outfit` and `photo`, and accepts either image bytes or Cloudflare's JSON envelope.
 * Nothing on the phone needs changing except which backend it is pointed at.
 *
 * The prompt is built here rather than on the phone because that is the work a Worker exists to
 * keep off the phone, and because it has to match the Mac pipeline exactly: a person's seed comes
 * from their character name so their repeat photos draw the SAME character, and that only holds
 * while the prompt is identical too. `src/prompt.js` is a port of `pipeline/restyle.py`, checked
 * against golden vectors generated by running the Python itself (`npm test`).
 */

const VISION = '@cf/google/gemma-4-26b-a4b-it'
const IMAGE = '@cf/black-forest-labs/flux-2-klein-4b'

/** Workers AI documents its input images as smaller than 512x512 and takes twice that in
 * practice. The larger is tried first because a face in a whole-body photo is only a few dozen
 * pixels across at the smaller one. */
const PHOTO_LIMITS = [1008, 504]

const json = (status, body) =>
  new Response(JSON.stringify(body), {
    status,
    headers: { 'content-type': 'application/json' },
  })

/** The first `{...}` in a model's reply. They wrap JSON in prose however firmly they are asked
 * not to. Greedy to the last brace, matching the Python's `re.search(r"\{.*\}", text, re.S)`. */
const jsonObjectIn = (text) => {
  if (typeof text !== 'string') return null
  const open = text.indexOf('{')
  const close = text.lastIndexOf('}')
  if (open < 0 || close <= open) return null
  try {
    return JSON.parse(text.slice(open, close + 1))
  } catch {
    return null
  }
}

/** What the vision model saw, or null. A failed description is not fatal: the Python draws from
 * the photo alone when it cannot get one, and so does this. */
async function describe(ai, photoBytes, closeUpBytes) {
  const asImage = (bytes) => ({
    type: 'image_url',
    image_url: { url: `data:image/png;base64,${base64(bytes)}` },
  })
  const content = [{ type: 'text', text: ASK }, asImage(photoBytes)]
  if (closeUpBytes) content.push(asImage(closeUpBytes))

  try {
    const answer = await ai.run(VISION, {
      messages: [{ role: 'user', content }],
      max_tokens: 700,
      // As close to deterministic as the model allows: a progress photo and an earlier one of
      // the same person should get back close to the same description, not a different word for
      // the same earrings each time, which a seeded draw would then follow.
      temperature: 0,
      chat_template_kwargs: { enable_thinking: false },
    })
    const text = answer?.response ?? answer?.choices?.[0]?.message?.content ?? ''
    return jsonObjectIn(text)
  } catch {
    return null
  }
}

function base64(bytes) {
  let binary = ''
  for (const byte of bytes) binary += String.fromCharCode(byte)
  return btoa(binary)
}

export default {
  async fetch(request, env) {
    if (request.method !== 'POST') return json(405, { error: 'POST a photo to this address.' })
    if (!env.AI) {
      return json(500, { error: 'This Worker has no AI binding. See wrangler.toml.' })
    }

    let form
    try {
      form = await request.formData()
    } catch {
      return json(400, { error: 'Expected a multipart form.' })
    }

    const photo = form.get('photo')
    if (!photo || typeof photo === 'string') {
      return json(400, { error: 'No photo in the request.' })
    }
    const name = String(form.get('name') ?? '')
    const outfit = knownOutfit(form.get('outfit'))
    // An outfit this pipeline does not know would otherwise quietly become a waist-up portrait
    // in the person's own clothes rather than the whole-body avatar that was asked for.
    if (form.get('outfit') && !outfit) {
      return json(400, { error: `Don't know the outfit "${form.get('outfit')}".` })
    }

    const photoBytes = new Uint8Array(await photo.arrayBuffer())
    const closeUp = form.get('close_up')
    const closeUpBytes =
      closeUp && typeof closeUp !== 'string'
        ? new Uint8Array(await closeUp.arrayBuffer())
        : null

    const seen = await describe(env.AI, photoBytes, closeUpBytes)
    const { facts, body } = features(seen ?? {}, outfit)
    const prompt = promptFor({ facts, body, outfit, closeUp: Boolean(closeUpBytes) })
    const size = sizeFor(outfit)
    const seed = await seedFor(name)

    // The Python's loop: the same draw, retried once at the smaller input size if the first is
    // refused. A used-up allowance ends it immediately, since the retry would be refused for the
    // same reason and would cost another call against tomorrow's count.
    let lastError = null
    for (const limit of PHOTO_LIMITS) {
      try {
        const drawn = await env.AI.run(IMAGE, {
          prompt,
          width: size.width,
          height: size.height,
          seed: String(seed),
          image: [...photoBytes],
          // the model takes the photo as the thing to edit; `limit` is carried so the retry is
          // a genuinely different request rather than the same bytes twice
          max_side: limit,
        })
        const image = drawn?.image
        if (typeof image === 'string') {
          const bytes = Uint8Array.from(atob(image), (c) => c.charCodeAt(0))
          return new Response(bytes, { headers: { 'content-type': 'image/png' } })
        }
        if (drawn instanceof ReadableStream) {
          return new Response(drawn, { headers: { 'content-type': 'image/png' } })
        }
        lastError = 'The image service sent something that was not an image.'
      } catch (error) {
        const detail = String(error?.message ?? error)
        if (/allocation|capacity|429/i.test(detail)) {
          return json(429, { error: "Today's image allowance is used up." })
        }
        lastError = detail
      }
    }
    // Deliberately not the raw error: whatever Cloudflare said goes to the logs, and the person
    // gets a sentence they can act on.
    console.log('draw failed:', lastError)
    return json(502, { error: 'Could not draw the avatar just now. Try again in a moment.' })
  },
}
